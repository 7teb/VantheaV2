const dropped = new Set<string>([...removed_names, ...Object.keys(added_values)]);

export const claude_env = (source: Readonly<Record<string, string | undefined>> = process.env): Record<string, string> => {
  const env: Record<string, string> = {};
  for (const [name, value] of Object.entries(source)) {
    if (value === undefined || dropped.has(name.toUpperCase())) {
      continue;
    }
    env[name] = value;
  }
  return { ...env, ...added_values };
};
